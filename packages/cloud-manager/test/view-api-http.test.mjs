import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import path from 'node:path';
import { Client, loginAdmin, startManager } from './helpers.mjs';
import { startFakeUpstream, UPSTREAM_KEY } from './fixtures/fake-upstream.mjs';

test('new operations complete over HTTP with tenant roles, sessions and CSRF', async (t) => {
  const upstream = await startFakeUpstream(); t.after(() => upstream.close());
  const env = await startManager({ relayCustomAllowPrivate: true }); t.after(() => env.stop());
  const { manager, config } = env;
  const origin = `http://127.0.0.1:${config.panelPort}`;
  const admin = await loginAdmin(manager);
  assert.equal((await new Client(origin).call('/api/admin/overview')).status, 401);
  assert.equal((await admin.call(`/api/admin/users/${admin.user.id}`, { method: 'PATCH', body: { disabled: true } })).json.code, 'LAST_ACTIVE_ADMIN');
  const created = await admin.call('/api/admin/users', { method: 'POST', body: { username: 'alice', password: 'alice-password' } });
  const viewed = await admin.call('/api/admin/users', { method: 'POST', body: { username: 'viewer', password: 'viewer-password' } });
  assert.equal(created.status, 201, created.text); assert.equal(viewed.status, 201, viewed.text);
  const tenantResponse = await admin.createTenant({ name: 'Fish', ownerUserId: created.json.user.id, days: 4 });
  assert.equal(tenantResponse.status, 201, tenantResponse.text);
  const tenantId = tenantResponse.json.tenant.id, base = `/api/tenants/${tenantId}`;
  manager.tenants.addMember(tenantId, viewed.json.user, 'viewer');
  const alice = new Client(origin), oldSession = new Client(origin), viewer = new Client(origin);
  assert.equal((await alice.login('alice', 'alice-password')).status, 200);
  assert.equal((await oldSession.login('alice', 'alice-password')).status, 200);
  assert.equal((await viewer.login('viewer', 'viewer-password')).status, 200);
  const ownerRole = await alice.call(base + '/members', { method: 'POST', body: { username: 'alice', role: 'viewer' } });
  assert.equal(ownerRole.status, 409); assert.equal(ownerRole.json.code, 'OWNER_ROLE_LOCKED');
  assert.equal((await alice.call(base + '/members', { method: 'POST', body: { username: 'viewer', role: 'owner' } })).status, 400);
  let listing = await alice.call('/api/tenants');
  assert.equal(listing.json.tenants[0].readiness.whitelistReady, false);
  assert.equal(listing.json.tenants[0].readiness.steps.length, 4);
  const tenant = manager.tenants.row(tenantId);
  fs.writeFileSync(path.join(tenant.data_dir, 'data', 'config.json'), JSON.stringify({ allow: { groups: ['123'], private: [] } }));
  assert.equal((await alice.call(base)).json.tenant.readiness.whitelistReady, true);
  assert.equal((await viewer.call(base + '/relay/custom/test', { method: 'POST', body: {} })).status, 403);
  assert.equal((await alice.call(base + '/relay/custom/test', { method: 'POST', csrf: false, headers: { origin }, body: {} })).json.code, 'CSRF_FAILED');
  const probe = await alice.call(base + '/relay/custom/test', { method: 'POST', body: { baseUrl: upstream.baseUrl, apiKey: UPSTREAM_KEY } });
  assert.equal(probe.status, 200, probe.text); assert.equal(probe.json.connected, true);
  assert.equal(probe.text.includes(UPSTREAM_KEY), false);
  assert.equal((await alice.call(base + '/relay/custom', { method: 'PUT', body: {
    baseUrl: upstream.baseUrl, apiKey: UPSTREAM_KEY, model: 'my-custom-model'
  } })).status, 200);
  const models = await alice.call(base + '/relay/models');
  assert.equal(models.status, 200, models.text);
  assert.equal(models.json.platformModel, tenant.default_model);
  assert.ok(models.json.platformModels.some((entry) => entry.id === tenant.default_model));
  assert.ok(models.json.models.some((entry) => entry.id === 'my-custom-model'));
  const first = await alice.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros: 123 } });
  const second = await alice.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros: 456 } });
  assert.equal(first.status, 201); assert.equal(second.status, 201);
  const pending = await admin.call('/api/admin/recharges?status=pending');
  assert.equal(pending.status, 200); assert.equal(pending.json.recharges.length, 2);
  assert.equal(pending.json.recharges[0].tenantName, 'Fish');
  const rejected = await admin.call(`/api/admin/recharges/${first.json.recharge.id}/reject`, { method: 'POST', body: { note: 'bad receipt' } });
  assert.equal(rejected.json.recharge.reviewNote, 'bad receipt');
  const before = manager.billing.wallet(tenantId).balanceMicros;
  const confirm = await admin.call(`/api/admin/recharges/${second.json.recharge.id}/confirm`, { method: 'POST', body: { note: 'approved' } });
  assert.equal(confirm.status, 200, confirm.text); assert.equal(confirm.json.billing.balanceMicros, before + 456);
  assert.equal((await admin.call(`/api/admin/recharges/${second.json.recharge.id}/confirm`, { method: 'POST' })).status, 409);
  const transactions = await viewer.call(base + '/billing/transactions');
  assert.equal(transactions.status, 200); assert.equal(transactions.json.transactions.filter((row) => row.kind === 'recharge').length, 1);
  const overview = await admin.call('/api/admin/overview');
  assert.equal(overview.status, 200, overview.text); assert.equal(overview.json.overview.tenants.total, 1);
  assert.equal(overview.json.overview.pendingRecharges.count, 0);
  const audit = await admin.call(`/api/admin/audit?tenantId=${tenantId}&action=billing.recharge.reject`);
  assert.equal(audit.json.entries.length, 1); assert.equal(audit.json.entries[0].actorUsername, 'admin');
  const userList = await admin.call('/api/admin/users');
  assert.equal(userList.json.users.find((entry) => entry.id === created.json.user.id).tenantCount, 1);
  const change = await alice.call('/api/auth/password', { method: 'PUT', body: { currentPassword: 'alice-password', newPassword: 'next-password' } });
  assert.equal(change.status, 200, change.text);
  assert.equal((await oldSession.call('/api/me')).status, 401);
  assert.equal((await alice.call('/api/me')).status, 200);
  assert.equal((await admin.call(`/api/admin/users/${created.json.user.id}`, { method: 'PATCH', body: { disabled: true } })).status, 200);
  assert.equal((await alice.call('/api/me')).status, 401);
  assert.equal((await admin.call(`/api/admin/users/${created.json.user.id}`, { method: 'PATCH', body: { disabled: false, password: 'reset-password' } })).status, 200);
  assert.equal((await alice.login('alice', 'reset-password')).status, 200);
});
