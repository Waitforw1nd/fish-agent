import assert from 'node:assert/strict';
import test from 'node:test';
import http from 'node:http';
import { Client, loginAdmin, request, startManager } from './helpers.mjs';
import { startFakeUpstream, UPSTREAM_KEY } from './fixtures/fake-upstream.mjs';
import { isPublicIp, resolveCustomUpstreamUrl } from '../src/relay/ssrf.js';

test('SSRF validation rejects private, mapped, mixed DNS and insecure destinations', async () => {
  for (const ip of ['127.0.0.1', '169.254.169.254', '10.0.0.1', '::1', '::ffff:7f00:1', '::ffff:a9fe:a9fe', 'fe80::1', 'fc00::1']) assert.equal(isPublicIp(ip), false, ip);
  assert.equal(isPublicIp('8.8.8.8'), true);
  assert.equal(isPublicIp('2606:4700:4700::1111'), true);
  for (const url of ['http://example.com', 'https://user:pass@example.com', 'https://127.0.0.1', 'https://[::ffff:7f00:1]']) {
    await assert.rejects(resolveCustomUpstreamUrl(url));
  }
  await assert.rejects(resolveCustomUpstreamUrl('https://example.com', { lookup: (_host, _opts, cb) => cb(null, [{ address: '8.8.8.8', family: 4 }, { address: '127.0.0.1', family: 4 }]) }));
  const resolved = await resolveCustomUpstreamUrl('https://example.com', { lookup: (_host, _opts, cb) => cb(null, [{ address: '8.8.8.8', family: 4 }]) });
  resolved.lookup('example.com', {}, (_err, address) => assert.equal(address, '8.8.8.8'));
});

test('custom relay, tenant isolation and manually confirmed recharge', async (t) => {
  const upstream = await startFakeUpstream();
  t.after(() => upstream.close());
  const env = await startManager({ relayCustomAllowPrivate: true });
  t.after(() => env.stop());
  const { manager, config } = env;
  const admin = await loginAdmin(manager);
  for (const name of ['alice', 'bob']) assert.equal((await admin.call('/api/admin/users', { method: 'POST', body: { username: name, password: `${name}-password-123`, role: 'user' } })).status, 201);
  const created = await admin.createTenant({ name: 'Custom tenant', slug: 'custom-tenant', planId: 'starter', ownerUsername: 'alice' });
  assert.equal(created.status, 201, created.text);
  const tenantId = created.json.tenant.id;
  const alice = new Client(`http://127.0.0.1:${config.panelPort}`);
  const bob = new Client(`http://127.0.0.1:${config.panelPort}`);
  await alice.login('alice', 'alice-password-123');
  await bob.login('bob', 'bob-password-123');
  const base = `/api/tenants/${tenantId}`;
  for (const route of ['/relay/custom', '/relay/logs', '/billing/recharges']) assert.equal((await bob.call(base + route)).status, 403);
  assert.equal((await bob.call(base + '/relay/custom', { method: 'PUT', body: {} })).status, 403);
  assert.equal((await bob.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros: 1 } })).status, 403);
  manager.db.prepare('INSERT INTO memberships (user_id, tenant_id, role, created_at) VALUES (?, ?, ?, ?)').run(bob.user.id, tenantId, 'viewer', Date.now());
  assert.equal((await bob.call(base + '/relay/custom')).status, 200);
  assert.equal((await bob.call(base + '/relay/logs')).status, 200);
  assert.equal((await bob.call(base + '/billing/recharges')).status, 200);
  assert.equal((await bob.call(base + '/relay/custom', { method: 'PUT', body: {} })).status, 403);
  assert.equal((await bob.call(base + '/relay/custom', { method: 'DELETE' })).status, 403);
  assert.equal((await bob.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros: 1 } })).status, 403);
  let response = await alice.call(base + '/relay/custom', { method: 'PUT', body: { baseUrl: upstream.baseUrl, model: 'deepseek-chat', apiKey: UPSTREAM_KEY } });
  assert.equal(response.status, 200, response.text);
  assert.equal(response.json.source, 'custom');
  assert.equal(response.text.includes(UPSTREAM_KEY), false);
  const stored = manager.db.prepare("SELECT ciphertext FROM tenant_secrets WHERE tenant_id = ? AND name = 'relay.custom.apiKey'").get(tenantId);
  assert.ok(stored && !stored.ciphertext.includes(UPSTREAM_KEY));
  response = await alice.call(base + '/relay/custom', { method: 'PUT', body: { model: 'deepseek-chat' } });
  assert.equal(response.status, 200, response.text);
  assert.equal((await alice.call(base + '/relay/custom', { method: 'PUT', body: { apiKey: '' } })).status, 400);
  const relayKey = manager.relayKeys.plaintext(tenantId);
  const relayBase = `http://127.0.0.1:${config.relayPort}`;
  const headers = { authorization: `Bearer ${relayKey}` };
  manager.db.prepare('UPDATE wallets SET balance_micros = 0 WHERE tenant_id = ?').run(tenantId);
  const body = { model: 'deepseek-chat', messages: [{ role: 'user', content: 'private prompt' }], max_tokens: 20 };
  const chat = await request(relayBase, { method: 'POST', path: '/v1/chat/completions', headers, body });
  assert.equal(chat.status, 200, chat.text);
  assert.equal(chat.headers['x-fish-cost-micros'], '0');
  const stream = await request(relayBase, { method: 'POST', path: '/v1/chat/completions', headers, body: { ...body, stream: true } });
  assert.equal(stream.status, 200, stream.text);
  assert.match(stream.text, /\[DONE\]/);
  assert.equal(manager.billing.wallet(tenantId).balanceMicros, 0);
  assert.equal(manager.db.prepare('SELECT COUNT(*) AS n FROM ledger WHERE tenant_id = ?').get(tenantId).n, 0);
  const logs = await alice.call(base + '/relay/logs?days=1&limit=2&model=deepseek-chat&status=success');
  assert.equal(logs.status, 200, logs.text);
  assert.equal(logs.json.logs.length, 2);
  for (const log of logs.json.logs) {
    assert.deepEqual(Object.keys(log).sort(), ['cost', 'error', 'latency', 'model', 'requestId', 'source', 'status', 'time', 'tokens'].sort());
    assert.equal(log.cost, 0); assert.equal(log.source, 'custom'); assert.ok(log.tokens > 0);
  }
  assert.equal(logs.text.includes('private prompt'), false);
  assert.equal(logs.text.includes(UPSTREAM_KEY), false);
  assert.equal((await alice.call(base + '/relay/logs?status=bad')).status, 400);
  assert.equal((await alice.call(base + '/relay/logs?limit=0')).status, 400);
  for (const amountMicros of [0, -1, 1.5, '12', null]) assert.equal((await alice.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros } })).status, 400);
  const order = await alice.call(base + '/billing/recharges', { method: 'POST', body: { amountMicros: 123456 } });
  assert.equal(order.status, 201, order.text);
  assert.equal(order.json.recharge.status, 'pending');
  assert.equal(manager.billing.wallet(tenantId).balanceMicros, 0);
  const confirmPath = `/api/admin/recharges/${order.json.recharge.id}/confirm`;
  assert.equal((await alice.call(confirmPath, { method: 'POST' })).status, 403);
  const confirmed = await admin.call(confirmPath, { method: 'POST' });
  assert.equal(confirmed.status, 200, confirmed.text);
  assert.equal(confirmed.json.recharge.status, 'confirmed');
  assert.equal(manager.billing.wallet(tenantId).balanceMicros, 123456);
  assert.equal((await admin.call(confirmPath, { method: 'POST' })).status, 409);
  assert.equal(manager.billing.wallet(tenantId).balanceMicros, 123456);
  assert.equal((await alice.call(base + '/billing/recharges')).json.recharges.length, 1);
  let redirected = 0;
  const target = http.createServer((_req, res) => { redirected++; res.end(); });
  await new Promise((resolve) => target.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => target.close(resolve)));
  const redirect = http.createServer((_req, res) => { res.writeHead(302, { location: `http://127.0.0.1:${target.address().port}/` }); res.end(); });
  await new Promise((resolve) => redirect.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise((resolve) => redirect.close(resolve)));
  assert.equal((await alice.call(base + '/relay/custom', { method: 'PUT', body: { baseUrl: `http://127.0.0.1:${redirect.address().port}` } })).status, 200);
  assert.equal((await request(relayBase, { method: 'POST', path: '/v1/chat/completions', headers, body })).status, 502);
  assert.equal(redirected, 0);
  assert.equal((await alice.call(base + '/relay/custom', { method: 'DELETE' })).json.source, 'platform');
  assert.equal(manager.secrets.has(tenantId, 'relay.custom.apiKey'), false);
});
