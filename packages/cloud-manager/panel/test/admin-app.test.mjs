import test from 'node:test';
import assert from 'node:assert/strict';
import { installDom, flush, findByText, fire } from './helpers/dom-stub.mjs';

const settle = async () => { for (let i = 0; i < 8; i++) await flush(); };

test('管理员应用挂载、指定所有者创建与异常路由', async () => {
  const document = installDom();
  const ids = ['boot-screen', 'boot-status', 'login-root', 'app-shell', 'view-root', 'sidebar', 'sidebar-toggle', 'sidebar-scrim', 'tenant-nav', 'platform-nav', 'user-nav', 'side-tenants', 'brand-link', 'nav-hosting', 'nav-relay', 'page-title', 'breadcrumb', 'user-avatar', 'user-name', 'user-role', 'logout-btn', 'theme-toggle', 'modal-root', 'toast-root', 'workspace-switch', 'password-btn'];
  for (const id of ids) { const el = document.createElement('div'); el.id = id; document.body.appendChild(el); }
  const nav = document.createElement('a');
  nav.setAttribute('data-nav', 'users'); nav.href = '#/users'; nav.textContent = '用户管理';
  document.getElementById('platform-nav').appendChild(nav);
  const listeners = {};
  globalThis.window = { addEventListener: (name, fn) => { listeners[name] = fn; }, scrollTo() {} };
  globalThis.localStorage = { setItem() {} };
  globalThis.location = { hash: '', origin: 'http://localhost' };
  const calls = [];
  const hostile = '<img src=x onerror=alert(1)>';
  let users = [{ id: 'alice', username: hostile, role: 'user' }];
  let tenants = [];
  let userStatus = 200;
  let usersStatus = 200;
  let deferred = null;
  const response = (body, status = 200) => ({ ok: status < 400, status, text: async () => JSON.stringify(body), headers: { get: () => null } });
  globalThis.fetch = async (path, init) => {
    calls.push({ path, method: init.method, body: init.body ? JSON.parse(init.body) : null, headers: init.headers });
    if (path === '/api/me') return response({ user: { id: 'admin', username: 'admin', role: 'admin' }, csrfToken: 'csrf-test' });
    if (path === '/api/admin/overview') return response({ overview: { tenants: {}, users: {}, pendingRecharges: { count: 0 }, drivers: [] } });
    if (path === '/api/tenants' && init.method === 'POST') {
      tenants.push({ id: 'new-fish', name: hostile, status: 'stopped', ownerUserId: 'alice' });
      return response({ ok: true, tenant: tenants[0] }, 201);
    }
    if (path === '/api/tenants') return response({ tenants });
    if (path === '/api/admin/users') return usersStatus === 200 ? response({ users }) : response({ error: '访问被拒绝' }, usersStatus);
    if (path === '/api/plans') return response({ plans: [{ id: 'trial', name: hostile, maxTenants: 1 }] });
    if (path === '/api/admin/users/alice/tenants') {
      if (deferred) return await deferred;
      if (userStatus !== 200) return response({ error: '访问被拒绝' }, userStatus);
      return response({ ok: true, user: users[0], tenants });
    }
    if (path === '/api/admin/users/missing/tenants') return response({ error: '用户不存在' }, 404);
    if (path === '/api/tenants/new-fish') return response({ tenant: tenants[0] });
    if (path.startsWith('/api/tenants/new-fish/')) return response({ ok: true });
    return response({ error: 'unexpected endpoint' }, 404);
  };
  const root = document.getElementById('view-root');
  const modal = document.getElementById('modal-root');
  const go = async (hash) => { location.hash = hash; listeners.hashchange(); await settle(); };
  await import('../app.js');
  await settle();
  assert.equal(location.hash, '#/admin/overview');
  listeners.hashchange(); await settle();
  assert.match(root.textContent, /运营总览/);
  assert.equal(document.getElementById('user-nav').hidden, true);
  document.getElementById('workspace-switch').click();
  assert.equal(location.hash, '#/user/instances');
  listeners.hashchange(); await settle();
  assert.equal(document.getElementById('platform-nav').hidden, true);
  assert.equal(document.getElementById('user-nav').hidden, false);
  document.getElementById('workspace-switch').click();
  assert.equal(location.hash, '#/admin/overview');
  listeners.hashchange(); await settle();
  await go('#/tenants');
  assert.match(root.textContent, /租户总览/);
  assert.equal(document.getElementById('platform-nav').hidden, false);
  await go(nav.href);
  assert.match(root.textContent, /用户管理/);
  assert.match(root.textContent, /<img src=x onerror=alert\(1\)>/);
  assert.equal(root.querySelectorAll('img').length, 0);
  const userLink = findByText(root, 'a', '查看拥有');
  assert.equal(userLink.href, '#/users/alice/instances');
  await go(userLink.href);
  assert.equal(findByText(document.getElementById('breadcrumb'), 'a', '用户管理').href, '#/users');
  assert.match(document.getElementById('breadcrumb').textContent, /用户实例/);
  assert.match(root.textContent, /还没有拥有的实例/);
  assert.equal(root.querySelectorAll('img').length, 0);
  findByText(root, 'button', '创建实例').click(); await settle();
  assert.equal(modal.querySelectorAll('img').length, 0);
  modal.querySelector('#admin-instance-name').value = '新实例';
  modal.querySelector('#admin-instance-plan').value = 'trial';
  findByText(modal, 'button', '创建实例').click(); await settle();
  const create = calls.find((call) => call.path === '/api/tenants' && call.method === 'POST');
  assert.deepEqual(create.body, { name: '新实例', ownerUserId: 'alice', planId: 'trial' });
  assert.equal(create.headers['X-CSRF-Token'], 'csrf-test');
  assert.match(root.textContent, /<img src=x onerror=alert\(1\)>/);
  assert.equal(root.querySelectorAll('img').length, 0);
  const hosting = findByText(root, 'a', 'Hosting').href;
  const relay = findByText(root, 'a', 'Relay').href;
  assert.equal(hosting, '#/tenants/new-fish/hosting');
  assert.equal(relay, '#/tenants/new-fish/relay');
  await go('#/tenants');
  assert.equal(findByText(root, 'a', '所属用户').href, '#/users/alice/instances');
  assert.match(root.textContent, /所属用户：<img src=x onerror=alert\(1\)>/);
  usersStatus = 403;
  await go('#/tenants');
  assert.match(root.textContent, /所属用户：alice/);
  assert.equal(findByText(root, 'a', '所属用户').href, '#/users/alice/instances');
  usersStatus = 200;
  await go(hosting);
  assert.match(root.textContent, /QQ 内核托管/);
  assert.ok(calls.some((call) => call.path === '/api/tenants/new-fish/qq/status'));
  await go(relay);
  assert.match(root.textContent, /Relay/);
  assert.ok(calls.some((call) => call.path === '/api/tenants/new-fish/relay/overview'));
  await go('#/users/missing/instances');
  assert.match(root.textContent, /用户实例加载失败/);
  assert.equal(findByText(root, 'button', '创建实例').disabled, true);
  userStatus = 403;
  await go('#/users/alice/instances');
  assert.match(root.textContent, /用户实例加载失败/);
  assert.equal(findByText(root, 'button', '创建实例').disabled, true);
  userStatus = 200;
  let resolveDeferred;
  deferred = new Promise((resolve) => { resolveDeferred = resolve; });
  await go('#/users/alice/instances');
  users = [];
  await go('#/users');
  assert.match(root.textContent, /还没有用户/);
  resolveDeferred(response({ user: { id: 'alice', username: 'stale' }, tenants: [{ id: 'old', name: '迟到实例' }] }));
  await settle();
  assert.match(root.textContent, /还没有用户/);
  assert.doesNotMatch(root.textContent, /迟到实例|stale/);
  usersStatus = 403;
  await go('#/users');
  assert.match(root.textContent, /用户列表加载失败/);
  usersStatus = 200;
  findByText(root, 'button', '重试').click();
  await settle();
  assert.match(root.textContent, /还没有用户/);
  await go('#/tenants/new-fish/agent');
  const whitelist = root.querySelector('textarea');
  whitelist.value = '123456';
  fire(whitelist, 'input');
  let leavePrompts = 0;
  globalThis.confirm = () => { leavePrompts++; return false; };
  try {
    await go('#/admin/overview');
    assert.equal(location.hash, '#/tenants/new-fish/agent');
    listeners.hashchange();
    await settle();
    assert.equal(leavePrompts, 1);
    assert.equal(root.querySelector('textarea'), whitelist);
    assert.equal(whitelist.value, '123456');
    globalThis.confirm = () => true;
    await go('#/admin/overview');
    assert.match(root.textContent, /运营总览/);
  } finally {
    delete globalThis.confirm;
  }
});
